-- Campus League schema for Supabase.
-- Run once in Supabase Dashboard > SQL Editor.
-- Quote rows marked "demo" are intentionally not tradable.

create table if not exists public.campus_schools (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists campus_schools_name_ci
  on public.campus_schools (lower(name));

create table if not exists public.campus_players (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 20),
  school_id bigint not null references public.campus_schools(id),
  joined_at timestamptz not null default now()
);

create table if not exists public.campus_wallets (
  user_id uuid primary key references public.campus_players(user_id) on delete cascade,
  cash_krw numeric(18,2) not null default 10000000 check (cash_krw >= 0),
  cash_usd numeric(18,4) not null default 0 check (cash_usd >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.market_quotes (
  symbol text primary key,
  market text not null check (market in ('KR','US','FX')),
  name text not null,
  price numeric(20,6) not null check (price > 0),
  currency text not null check (currency in ('KRW','USD')),
  change_pct numeric(10,4) not null default 0,
  source text not null default 'manual',
  freshness text not null default 'demo' check (freshness in ('demo','end_of_day','delayed','real_time')),
  is_tradable boolean not null default false,
  as_of timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.campus_trades (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.campus_players(user_id) on delete cascade,
  symbol text not null references public.market_quotes(symbol),
  side text not null check (side in ('buy','sell')),
  quantity integer not null check (quantity between 1 and 100000),
  price numeric(20,6) not null check (price > 0),
  currency text not null check (currency in ('KRW','USD')),
  fx_krw numeric(16,6) not null check (fx_krw > 0),
  created_at timestamptz not null default now()
);
create index if not exists campus_trades_player_time
  on public.campus_trades (user_id, created_at desc);

create table if not exists public.campus_fx_conversions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.campus_players(user_id) on delete cascade,
  krw_amount numeric(18,2) not null check (krw_amount > 0),
  usd_amount numeric(18,4) not null check (usd_amount > 0),
  fx_krw numeric(16,6) not null check (fx_krw > 0),
  created_at timestamptz not null default now()
);
create index if not exists campus_fx_player_time
  on public.campus_fx_conversions (user_id, created_at desc);

alter table public.campus_schools enable row level security;
alter table public.campus_players enable row level security;
alter table public.campus_wallets enable row level security;
alter table public.market_quotes enable row level security;
alter table public.campus_trades enable row level security;
alter table public.campus_fx_conversions enable row level security;

drop policy if exists "Public can read campus schools" on public.campus_schools;
create policy "Public can read campus schools"
  on public.campus_schools for select to anon, authenticated using (true);
drop policy if exists "Players can read own profile" on public.campus_players;
create policy "Players can read own profile"
  on public.campus_players for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Players can read own wallet" on public.campus_wallets;
create policy "Players can read own wallet"
  on public.campus_wallets for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Public can read market quotes" on public.market_quotes;
create policy "Public can read market quotes"
  on public.market_quotes for select to anon, authenticated using (true);
drop policy if exists "Players can read own trades" on public.campus_trades;
create policy "Players can read own trades"
  on public.campus_trades for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Players can read own conversions" on public.campus_fx_conversions;
create policy "Players can read own conversions"
  on public.campus_fx_conversions for select to authenticated using (user_id = (select auth.uid()));

